CREATE USER IF NOT EXISTS 'anne_nail_app'@'127.0.0.1'
  IDENTIFIED BY 'REEMPLAZAR_CON_DB_PASSWORD';
CREATE USER IF NOT EXISTS 'anne_nail_app'@'localhost'
  IDENTIFIED BY 'REEMPLAZAR_CON_DB_PASSWORD';

ALTER USER 'anne_nail_app'@'127.0.0.1'
  IDENTIFIED BY 'REEMPLAZAR_CON_DB_PASSWORD';
ALTER USER 'anne_nail_app'@'localhost'
  IDENTIFIED BY 'REEMPLAZAR_CON_DB_PASSWORD';

GRANT SELECT, INSERT, UPDATE, DELETE
  ON __DB_NAME__.*
  TO 'anne_nail_app'@'127.0.0.1';
GRANT SELECT, INSERT, UPDATE, DELETE
  ON __DB_NAME__.*
  TO 'anne_nail_app'@'localhost';

FLUSH PRIVILEGES;
